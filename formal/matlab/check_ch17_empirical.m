% check_ch17_empirical.m -- Ch. 17 (Empirical Evidence): numbers that can be
% re-derived from other numbers stated in the text (CIs, effect sizes,
% ratios, counts). Line numbers refer to source/Geometric-Ethics-v1.24.tex.
fprintf('\n--- check_ch17_empirical: Ch17 derived statistics ---\n');
z = norminv(0.975);
wilson = @(k,n) [ (k/n + z^2/(2*n) - z*sqrt(k/n*(1-k/n)/n + z^2/(4*n^2))) / (1+z^2/n), ...
                  (k/n + z^2/(2*n) + z*sqrt(k/n*(1-k/n)/n + z^2/(4*n^2))) / (1+z^2/n) ];
h = @(p1,p2) abs(2*asin(sqrt(p1)) - 2*asin(sqrt(p2)));   % Cohen's h

% --- 95% CIs of the semantic-gate rates (Wilson as stated; other methods tried too)
cp = @(k,n) [betainv(0.025,k,n-k+1), betainv(0.975,k+1,n-k)];
wald = @(k,n) k/n + [-1 1]*z*sqrt(k/n*(1-k/n)/n);
ac = @(k,n) (k+z^2/2)/(n+z^2) + [-1 1]*z*sqrt(((k+z^2/2)/(n+z^2))*(1-(k+z^2/2)/(n+z^2))/(n+z^2));
methods = {wilson, cp, wald, ac}; mnames = {'Wilson', 'Clopper-Pearson', 'Wald', 'Agresti-Coull'};
cases = {22311, 0.91, 582, [88.2 93.4], '"you promised" 91%'; ...
         22312, 0.94, 347, [91.1 96.2], '"only if convenient" 94%'};
for c = 1:size(cases,1)
    [ln, p, n, ci, lbl] = cases{c,:};
    best = []; bestErr = inf; okW = false; other = {};
    for k = 0:n
        if abs(round(100*k/n) - 100*p) > 1e-9, continue; end   % k/n must print as p
        for mth = 1:numel(methods)
            wv = 100*methods{mth}(k,n); err = max(abs(round(wv,1) - ci));
            if mth == 1 && err < bestErr, bestErr = err; best = [k wv]; end
            if err <= 0.1 + 1e-9
                if mth == 1, okW = true; else, other{end+1} = sprintf('%s k=%d', mnames{mth}, k); end %#ok<AGROW>
            end
        end
    end
    if isempty(other), otherTxt = 'Clopper-Pearson, Wald and Agresti-Coull do not match either'; else, otherTxt = ['matches instead: ' strjoin(unique(other), ', ')]; end
    ge_check('TEXT-Ch17', ln, okW, ...
        sprintf('%s, n=%d, 95%% Wilson CI [%.1f%%, %.1f%%] (tol 0.1 pp)', lbl, n, ci), ...
        sprintf('no count k/n printing as %g%% gives that Wilson CI; closest k=%d: [%.1f%%, %.1f%%] (book width %.1f pp); %s', ...
        100*p, best(1), best(2), best(3), ci(2)-ci(1), otherTxt));
end

