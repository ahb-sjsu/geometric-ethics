function p = local_fisher(a, n1, b, n2)
% two-sided Fisher exact test for successes a/n1 vs b/n2
K = a + b; N = n1 + n2;
x = max(0, K - n2):min(K, n1);
pr = exp(gammaln(n1+1)-gammaln(x+1)-gammaln(n1-x+1) + gammaln(n2+1)-gammaln(K-x+1)-gammaln(n2-K+x+1) ...
     - (gammaln(N+1)-gammaln(K+1)-gammaln(N-K+1)));
p0 = pr(x == a);
p = min(1, sum(pr(pr <= p0*(1+1e-7))));
end
